"""SQLAlchemy Core table metadata for the PostgreSQL datastore (ADR-0001 §2).

This module declares the current SQLite schema (``storage/db/schema.py`` plus
the tables created lazily by ``storage/db/investigations.py`` and
``storage/cleanup.py``) once, as Core ``MetaData``.  Alembic reads it for drift
checks (``alembic check``); the baseline revision creates the same shape.

Types are translated faithfully from SQLite affinities:

* ``TEXT``    -> ``text`` (timestamps and JSON stay text in the baseline);
* ``REAL``    -> ``double precision``;
* ``INTEGER`` -> ``bigint`` (SQLite integers are 64-bit);
* ``INTEGER PRIMARY KEY AUTOINCREMENT`` -> ``bigint GENERATED BY DEFAULT AS
  IDENTITY`` (by default, so the SQLite importer can keep existing ids).

The ADR-0002 tightening (``timestamptz``, ``jsonb``, provenance ``CHECK``s and
foreign keys) lands in later revisions, domain by domain, together with the
port of each ``Database`` mixin and its contract tests.
"""

from __future__ import annotations

