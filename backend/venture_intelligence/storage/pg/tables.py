NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)

# Tier 1 of ADR-0002 §3 that exists in the current schema: the evidence record.
# The baseline migration installs append-only triggers on exactly these tables.
APPEND_ONLY_TABLES: tuple[str, ...] = (
    "events",
    "observations",
    "candidate_rejections",
    "batch_discovery_observations",
)


def _pk(name: str) -> Column:
    return Column(name, Text, primary_key=True)


def _req(name: str, type_=Text, default: str | None = None) -> Column:
    server_default = None if default is None else text(default)
    return Column(name, type_, nullable=False, server_default=server_default)


def _opt(name: str, type_=Text) -> Column:
    return Column(name, type_, nullable=True)


