"""Generate docs/revamp/DECISIONS.md from one file per decision.

Each decision lives in ``docs/revamp/decisions/D-NNN-<slug>.md`` and starts
with::

    # D-NNN: <title>

    - **Date:** YYYY-MM-DD
    - **Area:** <short area>
    - **Differs from owner instruction:** <Yes/No/Partly ...>

Stacked branches that each add a decision then touch different files, so
they no longer conflict on a shared table. The index is generated, never
edited by hand.

Usage: ``python scripts/docs/decision_index.py`` writes the index;
``--check`` exits 1 when the committed index is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DECISIONS_DIR = ROOT / "docs" / "revamp" / "decisions"
INDEX = ROOT / "docs" / "revamp" / "DECISIONS.md"

FILE_RE = re.compile(r"^D-(\d{3})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$")
TITLE_RE = re.compile(r"^# (D-\d{3}): (.+)$")
FIELD_RE = re.compile(r"^- \*\*(Date|Area|Differs from owner instruction):\*\* (.+)$")

HEADER = """\
# Revamp decision log

<!-- Generated by scripts/docs/decision_index.py; do not edit by hand. -->

One file per decision lives in [`decisions/`](decisions/). Each states what was
chosen, what the owner instructed (if different), why the choice is better and
what trade-off it accepts, and how feature parity is preserved and verified.
Architecture-level choices also get an ADR in `docs/adr/`. To add a decision,
create `decisions/D-NNN-<slug>.md` and run `python scripts/docs/decision_index.py`.

| ID | Date | Area | Differs from owner instruction? | Decision |
|---|---|---|---|---|
"""


@dataclass(frozen=True)
class Decision:
    ident: str
    title: str
    date: str
    area: str
    differs: str
    path: Path


def parse(path: Path) -> Decision:
    if not FILE_RE.match(path.name):
        raise ValueError(f"{path.name}: expected D-NNN-<kebab-slug>.md")
    lines = path.read_text(encoding="utf-8").splitlines()
    title = TITLE_RE.match(lines[0]) if lines else None
    if not title:
        raise ValueError(f"{path.name}: first line must be '# D-NNN: <title>'")
    if not path.name.startswith(title.group(1)):
        raise ValueError(f"{path.name}: heading id {title.group(1)} does not match file name")
    fields = {m.group(1): m.group(2).strip() for m in map(FIELD_RE.match, lines) if m}
    missing = {"Date", "Area", "Differs from owner instruction"} - fields.keys()
    if missing:
        raise ValueError(f"{path.name}: missing {', '.join(sorted(missing))}")
    return Decision(
        ident=title.group(1),
        title=title.group(2).strip(),
        date=fields["Date"],
        area=fields["Area"],
        differs=fields["Differs from owner instruction"],
        path=path,
    )


def render(decisions_dir: Path = DECISIONS_DIR) -> str:
    decisions = sorted((parse(p) for p in decisions_dir.glob("*.md")), key=lambda d: d.ident)
    idents = [d.ident for d in decisions]
    duplicates = sorted({i for i in idents if idents.count(i) > 1})
    if duplicates:
        raise ValueError(f"duplicate decision ids: {', '.join(duplicates)}")
    rows = [
        f"| {d.ident} | {d.date} | {d.area} | {d.differs} | [{d.title}](decisions/{d.path.name}) |"
        for d in decisions
    ]
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the index is stale")
    args = parser.parse_args(argv)
    try:
        expected = render()
    except ValueError as exc:
        print(f"decision-index: {exc}", file=sys.stderr)
        return 1
    current = INDEX.read_text(encoding="utf-8").replace("\r\n", "\n") if INDEX.exists() else ""
    if args.check:
        if current != expected:
            print(
                "decision-index: DECISIONS.md is stale; run scripts/docs/decision_index.py",
                file=sys.stderr,
            )
            return 1
        return 0
    INDEX.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
